def ziwei_position(ju: int, lunar_day: int) -> int:
    """五行局数 + 农历生日(1-30) → 紫微所在宫位索引。

    查 ZIWEI_POS_TABLE（书源五张安紫微图），不做闭式拟合——
    书源各局初一落宫互异（水二丑 / 木三辰 / 金四亥 / 土五午 / 火六酉），
    且土五、火六两局内部不规则（歌诀自称「惟有九日不能均」「惟有六日无正位」），
    闭式公式无法同时满足（旧式 (局数×日) mod 12 与书源全部 148 格皆不符）。
    """
    row = ZIWEI_POS_TABLE.get(ju)
    if row is None:
        raise ValueError(f"五行局数 {ju} 不在 2-6 之内，无法定紫微")
    if not 1 <= lunar_day <= 30:
        raise ValueError(f"农历日 {lunar_day} 不在 1-30 之内，无法定紫微")
    branch = row[lunar_day - 1]
    if not branch:
        return -1
    return EARTHLY_BRANCHES.index(branch)


def tianfu_position(ziwei_pos: int) -> int:
    """天府位置：紫微与天府以寅申为轴对称（书源 2097「安天府圖」图注）。

    原文：「天府惟寅申二宫紫府同宫，余宫俱各填协作对，如紫居丑则府居卯矣。」
    即 天府 = (4 - 紫微) % 12：

      紫微在寅(2) → 天府在寅(2)（同宫）✓ 紫微在子(0) → 天府在辰(4) ✓
      紫微在丑(1) → 天府在卯(3)（图注原文所举）✓ 紫微在午(6) → 天府在戌(10) ✓

    自证：dev_tools/regression.py 的 B1 断言用卷二「一 命宫」各主星本宫诗的
    「X同度」明文（「与」字可省）逐格核对，核的就是本式加星系固定偏移。

    **格数不写死在这里**：它由回归运行时从 `data/star_brightness.json` 的
    `companions` 表算出、在 B1 那一行打印（该读数即当前基线）。计数口径
    （取「同度」前的全部宫位组、逐支展开、按 (星, 宫支) 去重、不要求「与」字）
    也只在回归里写一份，本处不重复，以免又一处的旧数过期。
    """
    return (4 - ziwei_pos) % 12


