# ============================================================ 五行局

# 书源 1665-1666：局数由**命宫干支纳音**定（「如甲生人安命在寅……是丙寅丁卯炉中火，
# 却去火局寻某日生期起紫微帝王」）。纳音→五行→局数：
WUXING_TO_JU: dict[str, int] = {"水": 2, "木": 3, "金": 4, "土": 5, "火": 6}

JU_TO_WUXING: dict[int, str] = {v: k for k, v in WUXING_TO_JU.items()}


def ju_from_ming_gong(year_stem: str, ming_gong_branch: str) -> int | None:
    """由年干 + 命宫地支（五虎遁配干）取命宫干支纳音，再定五行局数。

    出处：书源 1665-1666 + 「起五行寅例」（书源 1675）+ 「六十花甲子纳音歌」（书源 1679-1684）。
    纳音与五虎遁的唯一真值源在 `symbols` / `ganzhi_calendar`，此处只做「纳音→局数」映射。
    """
    if year_stem not in HEAVENLY_STEMS or ming_gong_branch not in EARTHLY_BRANCHES:
        return None
    from .ganzhi_calendar import TIGER_MONTH_STEM
    from .symbols import nayin_of, NAYIN_TO_ELEMENT

    idx = EARTHLY_BRANCHES.index(ming_gong_branch)
    stem = HEAVENLY_STEMS[(TIGER_MONTH_STEM[year_stem] + (idx - 2) % 12) % 10]
    nayin = nayin_of(stem + ming_gong_branch)
    if not nayin:
        return None
    return WUXING_TO_JU.get(NAYIN_TO_ELEMENT.get(nayin, ""))


