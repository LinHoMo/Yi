def hex2yao(hx_name):
    u, l = HT[hx_name]
    return TY[l] + TY[u]

cands = []
for name in HT:
    try:
        h = build_hexagram_result(hex2yao(name), "test", "manual", 2024, 6, 1, 10,
                                  explicit_time={"month_sb": "甲申", "day_sb": "庚辰"})
    except Exception:
        continue
    og = h["original_hexagram"]
    palace_elem = og.get("palace_element", "")
    resp_branch = None
    resp_rel = None
    resp_pos = None
    for y in og["yao_lines"]:
        if y.get("is_response"):
            resp_branch = y.get("earthly_branch", "")
            resp_rel = y.get("six_relation", "")
            resp_pos = y.get("position")
    if resp_branch == "酉" and resp_rel == "父母":
        cands.append((name, og.get("palace"), palace_elem, resp_pos))
